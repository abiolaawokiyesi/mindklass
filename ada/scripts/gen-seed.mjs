// Generates migrations/seed.sql from the authored curriculum.
// Keeps the DB mirror and the source-of-truth content provably in sync.
import { writeFileSync } from 'node:fs'
import { COURSES } from '../.tmp/courses.mjs'

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

let sql = `-- AUTO-GENERATED by scripts/gen-seed.mjs. Do not edit by hand.
-- Mirrors src/kb/courses.ts into D1 so retrieval can run in SQL.

`
let chunkCount = 0

for (const course of COURSES) {
  for (const lesson of course.lessons) {
    const payload = JSON.stringify(lesson)
    sql += `INSERT INTO kb_lesson (lesson_id, course_id, payload) VALUES (${q(lesson.id)}, ${q(course.id)}, ${q(payload)})
  ON CONFLICT(lesson_id) DO UPDATE SET payload = excluded.payload, updated_at = CURRENT_TIMESTAMP;

`
    const rows = [
      ...lesson.chunks.map((c, i) => ({ idx: i, title: c.title, body: c.body })),
      ...lesson.misconceptions.map((m, i) => ({
        idx: 1000 + i,
        title: `Common misconception in ${lesson.title}`,
        body: `Misconception: ${m.wrong} Correction: ${m.right}`
      })),
      ...lesson.glossary.map((g, i) => ({
        idx: 2000 + i,
        title: `Definition: ${g.term}`,
        body: `${g.term} — ${g.meaning}`
      }))
    ]
    for (const r of rows) {
      const kw = `${r.title} ${r.body} ${lesson.title} ${course.title}`.toLowerCase()
      sql += `INSERT INTO kb_chunk (course_id, lesson_id, chunk_idx, title, body, keywords) VALUES (${q(course.id)}, ${q(lesson.id)}, ${r.idx}, ${q(r.title)}, ${q(r.body)}, ${q(kw)})
  ON CONFLICT(lesson_id, chunk_idx) DO UPDATE SET title = excluded.title, body = excluded.body, keywords = excluded.keywords;

`
      chunkCount++
    }
  }
}

writeFileSync('migrations/seed.sql', sql)
console.log(`seed.sql written: ${COURSES.length} courses, ${COURSES.reduce((a, c) => a + c.lessons.length, 0)} lessons, ${chunkCount} chunks`)
