# Turns MindKlass lesson notes (patches\ng_courses.json) into a D1 seed so Ada answers
# from the real course notes. No Node needed.
#
#   powershell -NoProfile -File .\scripts\gen-mindklass-seed.ps1 -Pattern 'NG-SS2-BIO-*'
#   cd ada ; npx wrangler d1 execute mindklass-avatar-production --remote --file=migrations/0003_mindklass_notes.sql
#
# Free-plan note: D1 allows 5 million row reads a day and Ada reads one course per turn,
# so seed the courses you want Ada to teach rather than everything. -MaxChunks stops the
# file from growing past what a single course lookup (LIMIT 3000) can return.
param(
  [string]$Pattern = 'NG-SS2-*',
  [int]$MaxChunks = 6000,
  [string]$Out = (Join-Path (Split-Path -Parent $PSScriptRoot) 'migrations\0003_mindklass_notes.sql')
)
$ErrorActionPreference = 'Stop'
$src = Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) 'patches\ng_courses.json'
$all = Get-Content $src -Raw -Encoding UTF8 | ConvertFrom-Json
$q = { param($v) if ($null -eq $v) { 'NULL' } else { "'" + ([string]$v).Replace("'", "''") + "'" } }
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('-- AUTO-GENERATED by scripts/gen-mindklass-seed.ps1 from patches/ng_courses.json. Do not edit by hand.')
[void]$sb.AppendLine('CREATE TABLE IF NOT EXISTS kb_title (id TEXT PRIMARY KEY, title TEXT NOT NULL);')
$chunks = 0; $courses = 0; $units = 0
foreach ($prop in $all.PSObject.Properties) {
  if ($prop.Name -notlike $Pattern) { continue }
  $c = $prop.Value
  if ($chunks -ge $MaxChunks) { Write-Warning "stopped before $($prop.Name): reached -MaxChunks $MaxChunks"; break }
  $courses++
  $cid = $prop.Name
  $ctitle = "$($c.title)"
  if ($c.group) { $ctitle = "$($c.group), Term $($c.term)" }
  [void]$sb.AppendLine("INSERT INTO kb_title (id, title) VALUES ($(& $q $cid), $(& $q $ctitle)) ON CONFLICT(id) DO UPDATE SET title = excluded.title;")
  foreach ($u in $c.units) {
    $units++
    $lid = "${cid}:$($u.id)"
    [void]$sb.AppendLine("INSERT INTO kb_title (id, title) VALUES ($(& $q $lid), $(& $q $u.title)) ON CONFLICT(id) DO UPDATE SET title = excluded.title;")
    $rows = @()
    $kw = (@($u.keyWords) -join ', ')
    $rows += [pscustomobject]@{ t = "$($u.title): summary"; b = "$($u.summary) Key words: $kw." }
    foreach ($s in $u.sections) {
      $body = (@($s.p) -join ' ')
      if ($s.tbl) { foreach ($r in $s.tbl.rows) { $body += ' ' + ((@($r)) -join '; ') + '.' } }
      if ($s.ex -and $s.ex.b) { $body += ' ' + ((@($s.ex.b)) -join ' ') }
      if ($body.Trim().Length -gt 0) { $rows += [pscustomobject]@{ t = "$($s.h)"; b = $body.Trim() } }
    }
    $i = 0
    foreach ($r in $rows) {
      $keywords = ("$($r.t) $($r.b) $($u.title) $ctitle").ToLower()
      [void]$sb.AppendLine("INSERT INTO kb_chunk (course_id, lesson_id, chunk_idx, title, body, keywords) VALUES ($(& $q $cid), $(& $q $lid), $i, $(& $q $r.t), $(& $q $r.b), $(& $q $keywords)) ON CONFLICT(lesson_id, chunk_idx) DO UPDATE SET title = excluded.title, body = excluded.body, keywords = excluded.keywords;")
      $i++; $chunks++
    }
  }
}
[IO.File]::WriteAllText($Out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"wrote $Out : $courses courses, $units units, $chunks chunks, $([math]::Round((Get-Item $Out).Length/1MB,2)) MB"
