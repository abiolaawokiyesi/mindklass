/**
 * MindKlass Avatar Engine — application controller.
 *
 * Responsibilities, in the order a learner experiences them:
 *   1. Boot: read /api/health, load courses, load languages, start a session.
 *   2. Teach: run a lesson turn-by-turn, speaking each sentence and moving on.
 *   3. Converse: accept typed or spoken input at any moment, interrupt speech,
 *      and have Ada answer in the learner's chosen language.
 *   4. Measure: every explanation ends in a question; answers update mastery.
 */

import { api } from './api.js'
import { Rig } from './rig.js'
import { CanvasPortrait } from './renderer.js'
import { Speaker } from './speech.js'
import { Mic } from './stt.js'

const $ = (id) => document.getElementById(id)
const CFG = window.__MK__ || {}

/* ------------------------------------------------------------------ state */

const state = {
  health: null,
  courses: [],
  languages: [],
  activeCourse: null,
  activeLesson: null,
  lessonIndex: 0,
  lessonSteps: [],
  sessionId: null,
  learnerId: null,
  lang: 'en',
  history: [],
  busy: false,
  abortChat: null,
  speakingMode: 'browser',
  micOn: false
}

const rig = new Rig()
let renderer = null
let speaker = null
let mic = null

/* ------------------------------------------------------------- bootstrap */

async function boot() {
  const canvas = $('mk-canvas')
  renderer = new CanvasPortrait(canvas)

  speaker = new Speaker({
    rig,
    onState: (s) => {
      $('mk-speaking').hidden = s !== 'speaking'
    },
    onWord: (word) => {
      // Live caption follows the voice — critical for deaf learners and for
      // noisy classrooms.
      if (word && !state.busy) return
    }
  })

  resizeLoop()

  try {
    const [health, courses, langs] = await Promise.all([api.health(), api.courses(), api.languages()])
    state.health = health
    state.courses = courses.courses
    state.languages = langs.languages
    state.speakingMode = health.tts?.mode === 'neural' ? 'neural' : 'browser'
    renderStatus()
    renderCourses()
    renderLanguages()
    applyLang(state.lang, { silent: true })
  } catch (e) {
    setStatus('Offline — teaching from cache', 'warn')
  }

  await startSession()

  wireUI()

  // First lesson selection, or the one linked from the URL.
  const wanted = CFG.initialLesson
  if (wanted) {
    const course = state.courses.find((c) => true)
    await api.lesson(wanted).then((r) => openLesson(r.course.id, wanted)).catch(() => {})
  } else if (state.courses.length) {
    selectCourse(state.courses[0].id)
  }

  setStatus(
    state.speakingMode === 'neural' ? 'Ada is ready · neural voice' : 'Ada is ready · device voice',
    'ok'
  )
}

function resizeLoop() {
  const onResize = () => renderer?.resize()
  window.addEventListener('resize', onResize)
  // Observe the stage rather than the window: the grid reflows independently.
  if ('ResizeObserver' in window) {
    new ResizeObserver(onResize).observe($('mk-stage'))
  }

  let last = performance.now()
  const frame = (now) => {
    const dt = Math.min(0.05, (now - last) / 1000)
    last = now
    rig.update(dt)
    renderer?.draw(rig, dt)
    requestAnimationFrame(frame)
  }
  requestAnimationFrame(frame)
}

/* ------------------------------------------------------------------ status */

function setStatus(text, tone) {
  const el = $('mk-status-pill')
  el.textContent = text
  if (tone) el.dataset.tone = tone
  else el.removeAttribute('data-tone')
}

function renderStatus() {
  const h = state.health
  if (!h) return
  const mode = h.tutor?.mode === 'model' ? 'AI tutor' : 'Curriculum tutor'
  $('mk-mode-badge').textContent = mode
  $('mk-mode-badge').title =
    h.tutor?.mode === 'model'
      ? `Answers generated by ${h.tutor.model} and checked against approved course content.`
      : 'Answers are drawn directly from approved MindKlass course content. No external model is connected.'
}

/* ----------------------------------------------------------------- courses */

function renderCourses() {
  const wrap = $('mk-courses')
  wrap.innerHTML = ''
  $('mk-course-count').textContent = `${state.courses.length} subject${state.courses.length === 1 ? '' : 's'}`

  for (const c of state.courses) {
    const btn = document.createElement('button')
    btn.type = 'button'
    btn.className = 'mk-course'
    btn.style.setProperty('--course-accent', c.accent || '#6d8bff')
    btn.dataset.courseId = c.id
    btn.innerHTML = `
      <span class="mk-course-subject">${esc(c.subject)} · ${esc(c.level)}</span>
      <span class="mk-course-title">${esc(c.title)}</span>
      <span class="mk-course-meta">${c.lessonCount} lesson${c.lessonCount === 1 ? '' : 's'} · ${c.minutes} min</span>`
    btn.addEventListener('click', () => selectCourse(c.id))
    wrap.appendChild(btn)
  }
}

async function selectCourse(courseId) {
  state.activeCourse = courseId
  document.querySelectorAll('.mk-course').forEach((b) => {
    b.setAttribute('aria-current', String(b.dataset.courseId === courseId))
  })

  const course = await api.course(courseId)
  clearMessages()

  addMessage(
    'assistant',
    `${course.title}. ${course.blurb} I have ${course.lessons.length} lesson${
      course.lessons.length === 1 ? '' : 's'
    } ready. Press play and I will teach the first one, or just ask me anything about it.`,
    { tags: [course.subject, 'Ready'] }
  )

  renderSuggestions(course)
  state.pendingLesson = course.lessons[0]?.id || null
  const l = course.lessons[0]
  if (l) {
    $('mk-lesson-bar').hidden = false
    $('mk-lesson-title').textContent = l.title
    $('mk-lesson-step').textContent = `${l.minutes} min · ${course.lessons.length} lessons`
    $('mk-lesson-fill').style.width = '0%'
  }
}

function renderSuggestions(course) {
  const wrap = $('mk-suggestions')
  wrap.innerHTML = ''
  const prompts = [
    `Explain ${course.title} like I am new to it`,
    'Give me a worked example',
    'Test me with a question',
    'Why does this matter?'
  ]
  for (const p of prompts) {
    const b = document.createElement('button')
    b.type = 'button'
    b.className = 'mk-suggest'
    b.textContent = p
    b.addEventListener('click', () => send(p))
    wrap.appendChild(b)
  }
}

/* ------------------------------------------------------------------ lesson */

async function openLesson(courseId, lessonId) {
  const { course, lesson } = await api.lesson(lessonId)
  state.activeCourse = courseId
  state.activeLesson = lesson
  state.lessonIndex = 0
  state.lessonSteps = buildLessonSteps(lesson)

  $('mk-lesson-bar').hidden = false
  $('mk-lesson-title').textContent = lesson.title
  updateLessonProgress()

  const { session } = await api
    .startSession({ lang: state.lang, lessonId, name: null })
    .catch(() => ({ session: null }))
  if (session) state.sessionId = session.sessionId

  startLessonPlayback()
}

/**
 * A lesson is taught as a sequence of short spoken beats, not one long lecture.
 * Each beat is followed by a comprehension check, which is where the learning
 * actually happens.
 */
function buildLessonSteps(lesson) {
  const steps = []
  steps.push({ kind: 'say', text: lesson.opening, gesture: 'open' })

  lesson.objectives.forEach((o, i) => {
    steps.push({
      kind: 'say',
      text: `By the end of this lesson you should be able to: ${o}`,
      gesture: 'count',
      label: `Objective ${i + 1}`
    })
  })

  for (const chunk of lesson.chunks) {
    steps.push({ kind: 'say', text: `${chunk.title}. ${chunk.body}`, gesture: 'explain' })
  }

  for (const w of lesson.worked) {
    steps.push({ kind: 'say', text: `Let us work through one. ${w.prompt}`, gesture: 'point' })
    w.steps.forEach((s, i) => {
      steps.push({ kind: 'say', text: `Step ${i + 1}. ${s}`, gesture: 'count' })
    })
  }

  lesson.checks.forEach((c) => {
    const opts = c.options?.length ? ` Your options are: ${c.options.map((o, i) => `${i + 1}, ${o}`).join('; ')}.` : ''
    steps.push({
      kind: 'ask',
      text: `${c.q}${opts}`,
      answer: c.answer,
      why: c.why,
      gesture: 'point'
    })
  })

  steps.push({ kind: 'say', text: lesson.closing, gesture: 'celebrate' })
  steps.push({ kind: 'done', text: 'Lesson complete.' })
  return steps
}

function updateLessonProgress() {
  const n = state.lessonSteps.length || 1
  const pct = Math.round((state.lessonIndex / n) * 100)
  $('mk-lesson-fill').style.width = `${pct}%`
  $('mk-lesson-step').textContent = `Step ${Math.min(state.lessonIndex + 1, n)} of ${n}`
}

async function startLessonPlayback() {
  speaker.stop()
  state.playingLesson = true
  await speaker.unlock()
  runStep()
}

async function runStep() {
  if (!state.playingLesson) return
  const step = state.lessonSteps[state.lessonIndex]
  if (!step) return

  updateLessonProgress()

  if (step.kind === 'done') {
    state.playingLesson = false
    $('mk-lesson-fill').style.width = '100%'
    addMessage('assistant', 'That is the end of the lesson. Ask me anything you want to go over again.', {
      tags: ['Lesson complete']
    })
    $('mk-stage-controls')
    rig.setExpression('delighted')
    rig.gesture('celebrate', 0.9)
    return
  }

  applyGestureCue(step.gesture)
  addMessage('assistant', step.text, { tags: step.label ? [step.label] : [] })
  $('mk-caption').textContent = step.text
  await speakAndWait(step.text)

  state.lessonIndex += 1
  updateLessonProgress()

  if (step.kind === 'ask') {
    // Wait for the learner. Do not auto-advance past a question — that is the
    // difference between a lecture and a class.
    state.awaitingAnswer = { step }
    $('mk-input').focus()
    return
  }
  runStep()
}

function speakAndWait(text) {
  return new Promise((resolve) => {
    speaker.say(text, { onEnd: resolve })
  })
}

function applyGestureCue(name) {
  switch (name) {
    case 'point': rig.gesture('point', 0.7); rig.setExpression('curious'); break
    case 'count': rig.gesture('count', 0.6); rig.setExpression('focused'); break
    case 'open': rig.gesture('shrug', 0.5); rig.setExpression('warm'); break
    case 'celebrate': rig.gesture('celebrate', 0.9); rig.setExpression('delighted'); break
    default: rig.setExpression('focused')
  }
  $('mk-emotion').textContent = labelForExpression(rig.expression)
}

function labelForExpression(e) {
  return {
    neutral: 'Attentive',
    warm: 'Encouraging',
    curious: 'Curious',
    delighted: 'Pleased',
    thinking: 'Thinking',
    focused: 'Explaining',
    concerned: 'Careful'
  }[e] || 'Attentive'
}

/* -------------------------------------------------------------- conversation */

async function send(text) {
  const message = String(text || '').trim()
  if (!message || state.busy) return

  speaker.stop()
  state.playingLesson = false
  state.busy = true
  $('mk-send').disabled = true

  addMessage('user', message)
  $('mk-input').value = ''
  autoGrow($('mk-input'))

  const bubble = addMessage('assistant', '', { typing: true })
  let acc = ''
  let meta = null

  state.abortChat?.()
  state.abortChat = api.chat(
    {
      message,
      lang: state.lang,
      courseId: state.activeCourse,
      lessonId: state.activeLesson?.id || null,
      sessionId: state.sessionId,
      learnerId: state.learnerId,
      history: state.history.slice(-8),
      name: null
    },
    {
      onEvent: (ev) => {
        if (ev.type === 'meta') {
          meta = ev
          if (ev.cue) {
            rig.setExpression(ev.cue.expression)
            rig.gesture(ev.cue.gesture, ev.cue.energy)
            $('mk-emotion').textContent = labelForExpression(ev.cue.expression)
          }
          if (ev.sources?.length) {
            bubble.querySelector('.mk-msg-meta')?.remove()
            const m = document.createElement('div')
            m.className = 'mk-msg-meta'
            m.innerHTML =
              `<span class="mk-tag">${esc(ev.strategy)}</span>` +
              ev.sources
                .slice(0, 2)
                .map((s) => `<span class="mk-tag mk-tag-src">${esc(s.label)}</span>`)
                .join('')
            bubble.appendChild(m)
          }
          if (ev.mode && ev.mode !== state.health?.tutor?.mode) {
            $('mk-mode-badge').textContent = ev.mode === 'model' ? 'AI tutor' : 'Curriculum tutor'
          }
        }
        if (ev.type === 'delta') {
          acc += ev.text
          const body = bubble.querySelector('.mk-msg-body')
          if (body) {
            body.textContent = acc
            body.querySelector?.('.mk-typing')?.remove()
          }
          $('mk-caption').textContent = acc
          // Speak as soon as we have a sentence, so latency is hidden.
          speakSentenceChunk(ev.text)
        }
      },
      onDone: () => {
        bubble.querySelector('.mk-typing')?.remove()
        state.history.push({ role: 'user', content: message })
        state.history.push({ role: 'assistant', content: acc })
        finishTurn(meta, acc)
      },
      onError: () => {
        bubble.querySelector('.mk-typing')?.remove()
        const body = bubble.querySelector('.mk-msg-body')
        if (body && !acc) {
          body.textContent =
            'I could not reach the lesson service just now. Check the connection and try again — your question is saved.'
        }
        finishTurn(meta, acc)
      }
    }
  )
}

/** Queue a speakable unit as the stream arrives. */
function speakSentenceChunk(chunk) {
  const sentences = chunk
    .replace(/\s+/g, ' ')
    .split(/(?<=[.!?…])\s+/)
    .filter((s) => s.trim().length > 2)
  for (const s of sentences) speaker.say(s)
  if (sentences.length === 0 && chunk.trim().length > 0) {
    // Partial sentence: hold it until the next chunk flushes naturally. The
    // Speaker queue handles this because sentences are only sent when complete.
  }
}

function finishTurn(meta, text) {
  state.busy = false
  $('mk-send').disabled = false

  // Grade a pending lesson answer, if the learner was answering one.
  if (state.awaitingAnswer) {
    const step = state.awaitingAnswer.step
    const correct = gradeAnswer(text, step.answer)
    state.awaitingAnswer = null
    recordMastery(correct)
    if (correct) {
      rig.setExpression('delighted')
      rig.gesture('celebrate', 0.9)
      $('mk-emotion').textContent = 'Pleased'
      speaker.say('That is right. ' + (step.why || ''))
    }
    // Continue the lesson after the exchange settles.
    setTimeout(() => {
      state.lessonIndex += 1
      state.playingLesson = true
      runStep()
    }, 1400)
  }
  scrollMessages()
}

function gradeAnswer(learnerText, expected) {
  const norm = (s) =>
    String(s)
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9\s]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()

  const a = norm(learnerText)
  const b = norm(expected)
  if (!a || !b) return false
  if (a.includes(b) || b.includes(a)) return true

  // Token overlap is forgiving enough for spoken answers, strict enough not to
  // reward a random guess.
  const bt = new Set(b.split(' ').filter((t) => t.length > 2))
  const at = a.split(' ').filter((t) => t.length > 2)
  if (!bt.size || !at.length) return false
  let hit = 0
  for (const t of at) {
    for (const target of bt) {
      if (t === target || (t.length > 4 && (target.startsWith(t) || t.startsWith(target)))) {
        hit++
        break
      }
    }
  }
  return hit / bt.size >= 0.5
}

async function recordMastery(correct) {
  if (!state.learnerId || !state.activeLesson) return
  await api.recordMastery({ learnerId: state.learnerId, topicId: state.activeLesson.id, correct }).catch(() => {})
}

/* ------------------------------------------------------------------ session */

async function startSession() {
  try {
    const r = await api.startSession({
      lang: state.lang,
      lessonId: null,
      name: null
    })
    state.sessionId = r.sessionId
    state.learnerId = r.learnerId
    if (r.greeting && state.history.length === 0) {
      addMessage('assistant', r.greeting, { tags: ['Ada'] })
      $('mk-caption').textContent = r.greeting
    }
  } catch {
    /* teaching continues without persistence */
  }
}

/* --------------------------------------------------------------- languages */

function renderLanguages() {
  const list = $('mk-lang-list')
  list.innerHTML = ''
  const neural = Boolean(state.health?.tts?.mode === 'neural')
  for (const l of state.languages) {
    const b = document.createElement('button')
    b.type = 'button'
    b.className = 'mk-lang'
    b.dataset.code = l.code
    b.setAttribute('aria-current', String(l.code === state.lang))
    b.innerHTML = `${esc(l.native)}<small>${esc(l.label)}${
      neural ? '' : ' · device voice'
    }</small>`
    b.addEventListener('click', () => {
      applyLang(l.code)
      $('mk-lang-dialog').close()
    })
    list.appendChild(b)
  }
}

function applyLang(code, opts = {}) {
  const l = state.languages.find((x) => x.code === code) || { code: 'en', bcp47: 'en-NG', native: 'English' }
  state.lang = l.code
  speaker.setLang(l.code, l.bcp47)
  document.documentElement.lang = l.code
  $('mk-lang-code').textContent = l.code.toUpperCase()

  document.querySelectorAll('.mk-lang').forEach((b) => {
    b.setAttribute('aria-current', String(b.dataset.code === l.code))
  })
  document.body.dir = l.rtl ? 'rtl' : 'ltr'

  if (!opts.silent) {
    const notice = `Language set to ${l.native}. Ada will teach and listen in ${l.native} from now on.`
    addMessage('assistant', notice, { tags: [l.native] })
    if (state.lang === 'en') {
      speaker.say(notice)
    } else {
      // Greet in the chosen language so the learner hears the switch immediately.
      const lang = state.languages.find((x) => x.code === l.code)
      speaker.say(lang?.greeting || notice)
    }
    $('mk-caption').textContent = notice
  }
}

/* --------------------------------------------------------------------- mic */

function toggleMic() {
  if (state.micOn) {
    mic?.stop()
    state.micOn = false
    $('mk-mic').setAttribute('aria-pressed', 'false')
    return
  }
  speaker.stop()
  state.playingLesson = false

  if (!mic) mic = new Mic({ lang: state.lang, bcp47: currentBcp47() })
  mic.setLang(state.lang, currentBcp47())

  state.micOn = true
  $('mk-mic').setAttribute('aria-pressed', 'true')
  rig.setExpression('curious')
  $('mk-emotion').textContent = 'Listening'

  mic.start({
    onInterim: (t) => {
      $('mk-caption').textContent = t
    },
    onFinal: (t) => {
      state.micOn = false
      $('mk-mic').setAttribute('aria-pressed', 'false')
      if (t && t.trim()) send(t)
    },
    onError: (msg) => {
      state.micOn = false
      $('mk-mic').setAttribute('aria-pressed', 'false')
      toast(msg)
    }
  })
}

function currentBcp47() {
  return state.languages.find((l) => l.code === state.lang)?.bcp47 || 'en-NG'
}

/* -------------------------------------------------------------------- misc */

function addMessage(role, text, opts = {}) {
  const wrap = document.createElement('div')
  wrap.className = 'mk-msg'
  wrap.dataset.role = role
  const body = document.createElement('div')
  body.className = 'mk-msg-body'
  if (opts.typing) {
    body.innerHTML = '<span class="mk-typing"><span></span><span></span><span></span></span>'
  } else {
    body.textContent = text
  }
  wrap.appendChild(body)
  if (opts.tags?.length) {
    const m = document.createElement('div')
    m.className = 'mk-msg-meta'
    m.innerHTML = opts.tags.map((t) => `<span class="mk-tag">${esc(t)}</span>`).join('')
    wrap.appendChild(m)
  }
  $('mk-messages').appendChild(wrap)
  scrollMessages()
  return wrap
}

function clearMessages() {
  $('mk-messages').innerHTML = ''
}

function scrollMessages() {
  const el = $('mk-messages')
  el.scrollTop = el.scrollHeight
}

function autoGrow(el) {
  el.style.height = 'auto'
  el.style.height = Math.min(120, el.scrollHeight) + 'px'
}

function toast(msg) {
  const t = $('mk-toast')
  t.textContent = msg
  t.hidden = false
  clearTimeout(t._to)
  t._to = setTimeout(() => (t.hidden = true), 4200)
}

function esc(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]))
}

/* ---------------------------------------------------------------- wiring */

function wireUI() {
  $('mk-composer').addEventListener('submit', (e) => {
    e.preventDefault()
    send($('mk-input').value)
  })

  const input = $('mk-input')
  input.addEventListener('input', () => autoGrow(input))
  input.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      send(input.value)
    }
  })

  $('mk-mic').addEventListener('click', async () => {
    await speaker.unlock()
    toggleMic()
  })

  $('mk-play').addEventListener('click', async () => {
    await speaker.unlock()
    if (state.playingLesson) {
      state.playingLesson = false
      speaker.stop()
      toast('Paused. Press play to continue the lesson.')
      return
    }
    const lessonId = state.activeLesson?.id || state.pendingLesson
    if (!lessonId) {
      toast('Pick a course on the left first.')
      return
    }
    if (state.activeLesson?.id === lessonId && state.lessonSteps.length) {
      state.playingLesson = true
      runStep()
    } else {
      await openLesson(state.activeCourse, lessonId)
    }
  })

  $('mk-mute').addEventListener('click', async (e) => {
    const muted = !speaker.muted
    speaker.setMuted(muted)
    e.currentTarget.textContent = muted ? '🔇' : '🔊'
    e.currentTarget.setAttribute('aria-pressed', String(muted))
    if (muted) toast('Muted. Captions still follow Ada so you can read along.')
  })

  $('mk-lang').addEventListener('click', () => $('mk-lang-dialog').showModal())
  $('mk-help-btn').addEventListener('click', () => $('mk-help-dialog').showModal())

  $('mk-next').addEventListener('click', () => {
    if (!state.lessonSteps.length) return
    state.lessonIndex = Math.min(state.lessonIndex + 1, state.lessonSteps.length - 1)
    if (state.playingLesson) { speaker.stop(); runStep() } else updateLessonProgress()
  })

  $('mk-prev').addEventListener('click', () => {
    if (!state.lessonSteps.length) return
    state.lessonIndex = Math.max(0, state.lessonIndex - 1)
    if (state.playingLesson) { speaker.stop(); runStep() } else updateLessonProgress()
  })

  $('mk-exit-lesson').addEventListener('click', () => {
    state.playingLesson = false
    speaker.stop()
    $('mk-lesson-bar').hidden = true
    $('mk-lesson-fill').style.width = '0%'
  })

  // Keyboard shortcuts: space to talk is the one learners actually use.
  window.addEventListener('keydown', (e) => {
    const tag = (e.target.tagName || '').toLowerCase()
    if (tag === 'input' || tag === 'textarea') return
    if (e.code === 'Space') { e.preventDefault(); toggleMic() }
    if (e.key === 'Escape') speaker.stop()
  })

  // Release the mic when the tab is hidden.
  document.addEventListener('visibilitychange', () => {
    if (document.hidden && state.micOn) {
      mic?.stop()
      state.micOn = false
      $('mk-mic').setAttribute('aria-pressed', 'false')
    }
  })
}

