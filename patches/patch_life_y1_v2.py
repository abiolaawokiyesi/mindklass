#!/usr/bin/env python3
"""
One-Year Life Skills Academy (LIFE-Y1) redesign.

  1. Replaces the whole LIFE-Y1 course object with patches/lifey1_v2.json, built
     by lifey1_content/build_course.ps1 from the authored batches. Every unit now
     follows one learning loop (goals, warm-up, true story, discussion, big idea,
     method, worked example, mistakes, practice lab, reflection, takeaways) with a
     weekly challenge and three scenario-based quick checks. The 47 true stories
     are carried over verbatim; unit ids are unchanged so saved progress survives.
  2. Course-level assessmentType "project": the card and header chips, the header
     badge and the end-of-course panel stop showing an exam (0 Q / null% to pass /
     Term Assessment) and show Capstones and Portfolio instead. Other courses are
     unaffected: every swap only branches on assessmentType.
  3. A journey progress bar in the unit header and calmer quick-check wording.

The UI swaps live in patches/life_y1_ui_patches.json (generated by
lifey1_content/make_ui_spec.ps1) so this script and apply_life_y1_v2.ps1 share them.
Run after the other patches (needs the LIFE-Y1 object and the unit view in place).
"""
import json
import os
import sys

SRC = "assets/app.js"
HERE = os.path.dirname(os.path.abspath(__file__))

with open(SRC, encoding="utf-8", errors="surrogateescape") as fh:
    d = fh.read()

if '"assessmentType":"project"' in d:
    sys.exit("FAIL: already patched")

# --- 1. replace the course object -------------------------------------------
key = '"LIFE-Y1":{'
assert d.count(key) == 1, f"LIFE-Y1 key found {d.count(key)}x"
start = d.index(key) + len(key) - 1
depth, in_str, esc, end = 0, False, False, -1
for k in range(start, len(d)):
    c = d[k]
    if in_str:
        if esc:
            esc = False
        elif c == "\\":
            esc = True
        elif c == '"':
            in_str = False
    elif c == '"':
        in_str = True
    elif c in "{[":
        depth += 1
    elif c in "}]":
        depth -= 1
        if depth == 0:
            end = k
            break
assert end > 0, "end of LIFE-Y1 object not found"
with open(os.path.join(HERE, "lifey1_v2.json"), encoding="utf-8") as fh:
    new_course = fh.read()
json.loads(new_course)  # must be valid JSON
d = d[:start] + new_course + d[end + 1:]

# --- 2/3. UI swaps ------------------------------------------------------------
with open(os.path.join(HERE, "life_y1_ui_patches.json"), encoding="utf-8") as fh:
    swaps = json.load(fh)
for s in swaps:
    n = d.count(s["old"])
    assert n == 1, f"swap '{s['name']}': anchor found {n}x"
    d = d.replace(s["old"], s["new"], 1)

with open(SRC, "w", encoding="utf-8", errors="surrogateescape") as fh:
    fh.write(d)
print(f"  LIFE-Y1 rebuilt ({len(new_course):,} chars) + {len(swaps)} UI swaps")
